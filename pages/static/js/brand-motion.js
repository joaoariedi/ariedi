/* Brand motion: the hero field drifts, settles as you scroll, and has depth.
 *
 * - The incoming field lines drift left to right, toward the machine: each line's three waves
 *   travel at their own slow speed (the brand guide allows "slow drift of the incoming lines").
 * - Scrolling through the hero calms the turbulence: the visitor is the inhibitor, imposing order.
 * - The lines sit on three depth layers that lag the scroll (and follow a fine pointer) by
 *   different amounts; the offsets fade to zero at the ring, so every line still meets the machine.
 * - Noise to signal: a faint high-frequency jitter rides the far left of each line and fades out
 *   long before the rings. It ramps in over the first second, so frame zero stays the static
 *   drawing, and when the orange decision line lands (its CSS entrance, ~1.2 s) the field's
 *   noise and turbulence drop a notch: the decision is what filters noise into signal.
 * - The page grid becomes a fixed plane that slides at 75 % of the scroll, behind the content.
 *   It is a real element whose transform is set directly: a custom property on <html> would
 *   restyle the whole document on every scroll frame (measured: 47 % main-thread on a slow phone).
 *
 * Each line arrives at its own point on the outer ring (data-tx/data-ty), not at one shared point.
 * The rings, the orange decision line and the output lines never move. Nothing runs with
 * prefers-reduced-motion or Save-Data, or without JavaScript: the static drawing generated by
 * tools/gen_field.py is frame zero of this animation, computed from the same formula.
 */
(function () {
	'use strict';

	var TAU = Math.PI * 2;
	var FRAME_MS = 1000 / 30;              // the field redraws at 30 fps
	var WAVE_SPEED = [14, 22, 30];         // px/s each of a line's three waves travels rightward
	var CALM = 0.75;                       // share of the turbulence a full scroll removes
	var SCROLL_LAG = [0.16, 0.08, 0];      // back, middle, front: fraction of the scroll each lags
	var POINTER = [6, 13, 22];             // back, middle, front: px of pointer parallax
	var EDGE_TOP = 20, EDGE_BOTTOM = 10;   // soft overflow beyond the band (svg units; the clip
	                                       // leaves 10 below YMAX), never inside it
	var GRID = 18, GRID_RATE = 0.75;       // the page grid cell and its share of the scroll
	var DEEP = 720, DEEP_RATE = 0.3;       // the deep plane's tile (dust, major grid) and its share
	var PLANE_POINTER = [12, 5];           // deep, grid: px the planes shift with a fine pointer
	var NOISE = 1.6;                       // svg units of high-frequency jitter at the far left
	var NOISE_REACH = 0.36;                // share of the width over which the jitter fades out
	var NOISE_RAMP = 1.0;                  // s for the jitter to fade in from frame zero
	var LAND = 1.2, SETTLE = 0.6;          // s: the decision line lands, then the field settles
	var FILTER_NOISE = 0.45, FILTER_TURB = 0.12;  // how much noise/turbulence the landing removes

	var root = document.documentElement;
	var media = function (q) { return window.matchMedia ? window.matchMedia(q) : null; };
	var reduce = media('(prefers-reduced-motion: reduce)');
	var finePointer = media('(hover: hover) and (pointer: fine)');
	var saveData = !!(navigator.connection && navigator.connection.saveData);

	// Two canvases (tools/gen_field.py): wide for tablets and desktops, narrow for phones. CSS
	// shows one; the field animates that one, and switches when a resize crosses the breakpoint.
	var fields = Array.prototype.slice.call(document.querySelectorAll('.hero-field svg.field'));
	var hero = fields.length ? fields[0].closest('.section') : null;
	var svg = null;
	var lines = [];
	var YMIN, YMAX, W, H, FADE, PULL;

	function smooth(t) {
		t = t < 0 ? 0 : t > 1 ? 1 : t;
		return t * t * (3 - 2 * t);
	}

	// Identity inside the band, so frame zero is exactly the generator's drawing (which already
	// keeps every line between YMIN and YMAX); only drift or parallax that pushes a line past the
	// band is eased back, asymptotically, instead of being cut flat by the clip.
	function soft(y) {
		if (y < YMIN) return YMIN - EDGE_TOP * (1 - Math.exp((y - YMIN) / EDGE_TOP));
		if (y > YMAX) return YMAX + EDGE_BOTTOM * (1 - Math.exp((YMAX - y) / EDGE_BOTTOM));
		return y;
	}

	function r1(v) {
		return String(Math.round(v * 10) / 10);
	}

	function shownField() {
		for (var i = 0; i < fields.length; i++) {
			if (fields[i].getClientRects().length) return fields[i];
		}
		return null;
	}

	// Points the animation at the canvas on screen; the one it leaves goes back to its static frame.
	function useField() {
		var next = shownField();
		if (next === svg) return;
		lines.forEach(function (L) { L.el.setAttribute('d', L.d0); });
		// A canvas that was display:none starts its CSS entrance when shown; on a resize or a
		// rotation the decision line has already landed, so land it again without the replay.
		if (svg && next && next.getAnimations) {
			next.getAnimations({ subtree: true }).forEach(function (a) { a.finish(); });
		}
		svg = next;
		lines = [];
		if (svg) readField();
	}

	// A line's points, every 8 svg units up to its own point on the ring, and the per-point
	// factors of the generator's formula: wave fade, pull toward the target, jitter fade.
	function linePoints(tx) {
		var pts = { xs: [], fade: [], pull: [], nfade: [] };
		for (var x = 0; x < tx; x += 8) pts.xs.push(x);
		pts.xs.push(tx);
		pts.xs.forEach(function (x) {
			pts.fade.push(1 - smooth((x / tx - FADE) / (1 - FADE)));
			pts.pull.push(Math.pow(x / tx, PULL));
			pts.nfade.push(1 - smooth(x / (W * NOISE_REACH)));
		});
		return pts;
	}

	function readField() {
		var ds = svg.dataset, vb = svg.viewBox.baseVal;
		YMIN = +ds.ymin; YMAX = +ds.ymax; W = vb.width; H = vb.height; FADE = +ds.fade; PULL = +ds.pull;
		Array.prototype.forEach.call(svg.querySelectorAll('.field-depth path[data-w]'), function (el) {
			var w = el.getAttribute('data-w').split(',').map(Number);
			lines.push({
				el: el,
				d0: el.getAttribute('d'),
				y0: +el.getAttribute('data-y0'),
				k: +el.getAttribute('data-k'),
				ty: +el.getAttribute('data-ty'),
				pts: linePoints(+el.getAttribute('data-tx')),
				depth: +el.parentNode.getAttribute('data-depth'),
				w: w,
				seed: lines.length * 1.7,
				om: [TAU * WAVE_SPEED[0] / w[1], TAU * WAVE_SPEED[1] / w[4], TAU * WAVE_SPEED[2] / w[7]]
			});
		});
	}

	// The generator's formula, with time, calm and the depth offsets (all in svg units).
	// Only the visible span is computed: where the box is wider than the canvas's shape, the
	// drawing is cropped from the left ("slice"), and those points are never drawn.
	function pathFor(line, t, amp, ox, oy, noise) {
		var w = line.w, om = line.om, sd = line.seed, P = line.pts, out = 'M', i, x, f, p, d, y;
		var from = Math.min(first, P.xs.length - 2);
		for (i = from; i < P.xs.length; i++) {
			x = P.xs[i]; f = P.fade[i]; p = P.pull[i]; d = 0;
			if (f > 0) {
				d = (w[0] * Math.sin(TAU * x / w[1] + w[2] - om[0] * t) +
					w[3] * Math.sin(TAU * x / w[4] + w[5] - om[1] * t) +
					w[6] * Math.sin(TAU * x / w[7] + w[8] - om[2] * t)) * f * line.k * amp;
			}
			if (noise > 0 && P.nfade[i] > 0) {
				d += noise * P.nfade[i] * Math.sin(x * 0.19 + t * 4.3 + sd) * Math.sin(x * 0.071 - t * 2.9 + sd * 1.3);
			}
			y = soft(line.y0 + d + oy * (1 - p)) * (1 - p) + line.ty * p;
			out += (i > from ? ' L' : '') + r1(x + ox * (1 - p)) + ' ' + r1(y);
		}
		return out;
	}

	var running = false, inView = true, last = 0, start = 0, unit = 1, first = 0;
	var scrollY = window.pageYOffset || 0, target = { x: 0, y: 0 }, ptr = { x: 0, y: 0 };

	function measure() {
		if (!svg) return;
		var r = svg.getBoundingClientRect();
		unit = Math.max(r.width / W, r.height / H) || 1;   // css px per svg unit ("slice")
		// Anchored right (xMaxYMid): the leftmost visible svg x, less a cell of margin. Every line
		// shares the 8-unit grid, so the first visible point has the same index on all of them.
		var left = W - r.width / unit - GRID;
		first = Math.max(0, Math.floor(left / 8));
	}

	function frame(now) {
		if (!running) return;
		window.requestAnimationFrame(frame);
		if (now - last < FRAME_MS) return;
		last = now;
		ptr.x += (target.x - ptr.x) * 0.1;
		ptr.y += (target.y - ptr.y) * 0.1;
		var t = (now - start) / 1000;
		var calm = 1 - CALM * smooth(scrollY / (hero.offsetHeight * 0.8));
		var landed = smooth((t - LAND) / SETTLE);
		var amp = calm * (1 - FILTER_TURB * landed);
		var noise = NOISE * smooth(t / NOISE_RAMP) * (1 - FILTER_NOISE * landed) * calm;
		for (var i = 0; i < lines.length; i++) {
			var L = lines[i], dp = L.depth;
			var ox = ptr.x * POINTER[dp] / unit;
			var oy = (ptr.y * POINTER[dp] * 0.6 + SCROLL_LAG[dp] * scrollY) / unit;
			L.el.setAttribute('d', pathFor(L, t, amp, ox, oy, noise));
		}
	}

	function play() {
		if (hero) hero.classList.toggle('field-paused', !inView || document.hidden);
		if (running || !inView || document.hidden || !lines.length) return;
		running = true;
		last = 0;
		window.requestAnimationFrame(frame);
	}

	function pause() {
		running = false;
		if (hero) hero.classList.add('field-paused');   // the decision pulse rests with the field
	}

	// Three speeds you can see: the deep plane (space dust, major grid) at 30 % of the scroll, the
	// drafting grid at 75 %, the content at 100 %. Each plane moves within one tile, in whole px.
	var gridQueued = false, plane = null, deep = null, lastShift = null, lastDeep = null;
	function shiftGrid() {
		gridQueued = false;
		var shift = -Math.round((scrollY * GRID_RATE) % GRID);
		var deepShift = -Math.round((scrollY * DEEP_RATE) % DEEP);
		if (plane && shift !== lastShift) {
			plane.style.transform = 'translate3d(0,' + shift + 'px,0)';
			lastShift = shift;
		}
		if (deep && deepShift !== lastDeep) {
			deep.style.transform = 'translate3d(0,' + deepShift + 'px,0)';
			lastDeep = deepShift;
		}
	}

	function onScroll() {
		scrollY = window.pageYOffset || 0;
		if (!gridQueued) {
			gridQueued = true;
			window.requestAnimationFrame(shiftGrid);
		}
	}

	function onPointer(e) {
		target.x = (e.clientX / window.innerWidth) * 2 - 1;
		target.y = (e.clientY / window.innerHeight) * 2 - 1;
		// the planes follow the pointer through the CSS translate property, eased by a transition,
		// so the scroll (transform) stays instant
		if (deep) deep.style.translate = (-target.x * PLANE_POINTER[0]) + 'px ' + (-target.y * PLANE_POINTER[0] * 0.6) + 'px';
		if (plane) plane.style.translate = (-target.x * PLANE_POINTER[1]) + 'px ' + (-target.y * PLANE_POINTER[1] * 0.6) + 'px';
	}

	function onResize() {
		useField();
		measure();
	}

	var observer = null;
	function enable() {
		if (!plane) {
			plane = document.createElement('div');
			plane.className = 'grid-plane';
			plane.setAttribute('aria-hidden', 'true');
			document.body.insertBefore(plane, document.body.firstChild);
			deep = document.createElement('div');
			deep.className = 'depth-plane';
			deep.setAttribute('aria-hidden', 'true');
			document.body.insertBefore(deep, plane);   // first in the DOM: painted furthest back
		}
		root.classList.add('motion-ok');
		onScroll();
		window.addEventListener('scroll', onScroll, { passive: true });
		if (!hero) return;
		useField();
		measure();
		start = window.performance.now();
		window.addEventListener('resize', onResize);
		if (finePointer && finePointer.matches) window.addEventListener('pointermove', onPointer, { passive: true });
		if ('IntersectionObserver' in window) {
			observer = new IntersectionObserver(function (entries) {
				inView = entries[0].isIntersecting;
				if (inView) play(); else pause();
			});
			observer.observe(hero);
		}
		play();
	}

	function disable() {
		pause();
		root.classList.remove('motion-ok');
		if (plane) { plane.style.transform = ''; plane.style.translate = ''; lastShift = null; }
		if (deep) { deep.style.transform = ''; deep.style.translate = ''; lastDeep = null; }
		window.removeEventListener('scroll', onScroll);
		window.removeEventListener('resize', onResize);
		window.removeEventListener('pointermove', onPointer);
		if (observer) { observer.disconnect(); observer = null; }
		lines.forEach(function (L) { L.el.setAttribute('d', L.d0); });   // back to the static frame
	}

	if (saveData) return;
	document.addEventListener('visibilitychange', function () {
		if (document.hidden) pause(); else if (root.classList.contains('motion-ok')) play();
	});
	if (reduce && reduce.addEventListener) {
		reduce.addEventListener('change', function () {
			if (reduce.matches) disable(); else enable();
		});
	}
	if (!reduce || !reduce.matches) enable();
})();
